#!/usr/bin/env python3
"""Aggregate results/crosspump/**/summary.json into the paper tables (mean +- std over seeds, per dataset x method).

    python3 scripts/xp_make_tables.py --results results/crosspump --fmt markdown [--metric P@FAR0.01] [--out docs/crosspump_tables.md]
"""
from __future__ import annotations
import argparse
import glob
import json
import os
from collections import defaultdict
import numpy as np
import pandas as pd

MAIN = ["AUC_PR_rows", "P@FAR0.01", "R@FAR0.01", "event_recall", "share_early_vs_anchor", "lead_anchor_min_mean", "lead_peak_min_median", "alarm_rate_normal_rows",
        "alarm_budget_error", "loss_avoided_bps", "loss_avoided_share", "avoid_share", "HR@5", "SR", "EAR", "n_trades"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results/crosspump"); ap.add_argument("--fmt", default="markdown"); ap.add_argument("--out", default=None)
    ap.add_argument("--metrics", nargs="*", default=MAIN); ap.add_argument("--tag", default="main")
    a = ap.parse_args()
    rows = []
    for f in glob.glob(os.path.join(a.results, "*", "*", "*", "seed*", "summary.json")):
        parts = f.split(os.sep)
        ds, bl, tag, seed = parts[-5], parts[-4], parts[-3], parts[-2]
        if a.tag != "all" and tag != a.tag:
            continue
        agg = json.load(open(f)).get("agg", {})
        rows.append({"dataset": ds, "method": bl, "tag": tag, "seed": seed, **{k: agg.get(k, np.nan) for k in a.metrics}})
    if not rows:
        print("no results found under", a.results); return
    df = pd.DataFrame(rows)
    out_lines = []
    for ds, g in df.groupby("dataset"):
        tab = g.groupby(["method", "tag"])[a.metrics].agg(["mean", "std"])
        tab.columns = [f"{m}_{s}" for m, s in tab.columns]
        tab["n_seeds"] = g.groupby(["method", "tag"]).size()
        txt = tab.round(3).to_markdown() if a.fmt == "markdown" else tab.round(3).to_string()
        out_lines.append(f"\n### {ds}\n\n{txt}\n")
    text = "\n".join(out_lines)
    print(text)
    if a.out:
        with open(a.out, "w") as fh:
            fh.write("# CrossPump result tables (auto-generated by scripts/xp_make_tables.py)\n" + text)


if __name__ == "__main__":
    main()
