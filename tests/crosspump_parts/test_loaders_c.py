def test_d10():
    with warnings.catch_warnings(record=True) as rec:
        warnings.simplefilter("always")
        panel = DATASETS.get("xp_memechain")({"root": FIX}).build_panel()
    assert any("TABULAR-ONLY" in str(w.message) for w in rec)
    es = check_common(panel, "xp_memechain", tabular=True)
