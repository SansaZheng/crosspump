    f = panel.price_feat[pre]
    assert np.isfinite(f[:, 0]).all() and np.isfinite(f[:, 4]).all() and np.isnan(f[:, 1]).all() and (f[:, 3] == 0).all()
    tf, names = m["tabular_features"], m["tabular_feature_names"]
    assert tf.shape == (13, len(names)) and not any("Quarter 3" in n or "Quarter 4" in n or "end date" in n for n in names), "outcome column among the features"
    assert np.allclose(f[:, 0], np.log(tf[:, 1] / tf[:, 0]), atol=1e-5) and np.allclose(panel.mid[pre], tf[:, 1])
    assert np.allclose(f[:, 4], np.log1p(tf[:, 2]), atol=1e-4), "thousands separators / nbsp not parsed"
    assert np.isnan(tf[:, names.index("Google results for project website (first day)")]).sum() == 1          # the '-' cell
    cov = m["coverage"]["episodes_with_platform"]
    assert cov == {"social": 13, "wallet": 13, "orderflow": 0}, cov
    soc = es.subset(es.platform == 0)
    assert len(soc) == 14, len(soc)                                   # 13 midpoint events + 1 first-day event inside the window
    assert np.isclose(soc.time, pre).sum() == 13 and (soc.avail == soc.time).all()
    assert all(k.count("@") == 1 and "USD@" in k for k in panel.assets)
    assert m["streams_are_summaries"] is True and "NC" in m["licence"]
    expect_missing(d9_rugpull1k, "xp_rugpull1k", "rugpull1k")
    print(f"ok  xp_rugpull1k  T={panel.T} N={panel.N} scam={m['n_pumps']} normal={m['n_controls']} events={m['coverage']['n_events']} (tabular_only, excluded from lead_time)")


