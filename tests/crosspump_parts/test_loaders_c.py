    assert m["coverage"]["episodes_with_platform"] == {"social": 10, "wallet": 0, "orderflow": 0}, m["coverage"]
    assert set(es.platform.tolist()) == {0} and np.allclose(es.time, m["pre_bars"]) and set(es.mark[:, 1].tolist()) <= {1.0, 2.0, 3.0}
    assert es.mark[:, 3].max() >= 0 and (es.source != 0).all()
    sub = DATASETS.get("xp_memechain")({"root": FIX, "max_controls": 4, "seed": 3}).build_panel()
    assert sub.N == 6 and sub.meta["n_pumps"] == 2

    cfg = {"root": FIX, "subdir": "crosspump/memechain_trades", "quiet_hours": 48, "burst_warmup": 6}
    p = DATASETS.get("xp_memechain")(cfg).build_panel()
    es = check_common(p, "xp_memechain")
    m = p.meta
    assert m["mode"] == "trades" and p.N == 4 and m["skipped"]["too_few_bars"] == 1, (p.N, m["skipped"])
    eps = {e["ticker"]: e for e in m["episodes"]}
    assert eps["MM0"]["is_pump"] and eps["MM0"]["ceased_within_24h"] and eps["MM1"]["is_pump"] and eps["MM1"]["chainpatrol_blocked"] and not eps["MM1"]["ceased_within_24h"]
    assert not eps["MM2"]["is_pump"] and not eps["MM4"]["is_pump"]
    i = p.assets.index(eps["MM0"]["key"])
    assert m["peak_row"][i] == 4 + 8 and eps["MM0"]["peak_source"] == "curated", m["peak_row"][i]       # first trade at hh:10, peak 2 h 01 min later
    assert 4 + 23 <= m["cease_row"][i] <= 4 + 24 and np.isnan(p.mid[m["cease_row"][i] + 1 :, i]).all(), "no bar may exist after the last trade"
    assert np.isnan(p.mid[:4, i]).all(), "no bar may exist before the launch"
    assert "collapse" in m["lead_time_reference"]
    cov = m["coverage"]["episodes_with_platform"]
    assert cov["wallet"] == 4 and cov["orderflow"] >= 1 and cov["social"] >= 2, cov
    wal = es.subset(es.platform == 1)
