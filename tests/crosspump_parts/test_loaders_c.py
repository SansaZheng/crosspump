def check_common(panel, name, tabular=False):
    panel.validate()
    m = panel.meta
    T, N = panel.mid.shape
    assert m["dataset"] == name and m["split_axis"] == "assets" and m["assets_time_aligned"] is False
    assert T == m["pre_bars"] + m["post_bars"] + 1 and len(panel.assets) == N == len(set(panel.assets))
    is_pump, peak, pre, lead = np.asarray(m["is_pump"]), np.asarray(m["peak_row"]), m["pre_bars"], m["lead"]
    assert is_pump.dtype == bool and is_pump.shape == (N,) and is_pump.any() and (~is_pump).any()
    assert (np.diff(m["anchor_ns"]) >= 0).all(), "episodes must be sorted by anchor time"
    rows = np.arange(T)
    for i in range(N):
        lab = panel.labels[:, i]
        if not is_pump[i]:
            assert lab.sum() == 0 and np.isnan(panel.bars_to_peak[:, i]).all()
            continue
        lo = max(0, pre - lead)
        want = (rows >= lo) & (rows <= peak[i])
        assert (lab.astype(bool) == want).all(), f"{name}: labels of episode {i} are not on [anchor - lead, peak]"
        btp = panel.bars_to_peak[:, i]
        fin = np.isfinite(btp)
        assert fin[want].all() and (btp[fin] == peak[i] - rows[fin]).all(), f"{name}: bars_to_peak not exact"
        assert (panel.avail_label[want, i] >= peak[i]).all(), "label knowable before the peak"
    assert (panel.avail_feat == rows[:, None]).all() and (panel.avail_label >= rows[:, None]).all()
    assert panel.universe.shape == (T, N)
    if panel.text is not None:
        assert (panel.avail_text >= rows[:, None, None]).all()
    es = get_streams(panel)
    assert es is not None and len(es) > 0, f"{name}: no streams"
    es.validate(T, N)
    assert (es.avail >= es.time - 1e-9).all()
    cov = m["coverage"]
    assert isinstance(cov, dict) and set(cov["episodes_with_platform"]) == {"social", "wallet", "orderflow"} and "note" in cov
    assert isinstance(m["assumptions"], list) and len(m["assumptions"]) >= 3
    assert m["licence"] and m["source"]
    assert bool(m.get("tabular_only", False)) == tabular
    if tabular:
        assert m["excluded_from"] == ["lead_time"] and not panel.tradable.any()
        other = np.delete(np.arange(T), pre)
        assert np.isnan(panel.mid[other]).all() and np.isnan(panel.price_feat[other][..., 0]).all()
    return es


def expect_missing(mod, key, token):
    empty = os.path.join(TMP, "empty_root"); os.makedirs(empty, exist_ok=True)
    try:
        DATASETS.get(key)({"root": empty}).build_panel()
    except FileNotFoundError as e:
        msg = str(e)
        assert "Download recipe" in msg and token in msg and mod.RECIPE.splitlines()[0] in msg, msg[:300]
        return
    raise AssertionError(f"{key}: missing raw files did not raise FileNotFoundError")


# ------------------------------------------------------------------------------------------------ onchain_utils
def test_utils():
    rng = np.random.default_rng(0)                                   # test-only data
    x = rng.normal(size=400); x[[5, 50, 51, 200]] = np.nan
    a, b = ou.causal_z(x, 30, 60.0), _causal_z(x, 30, 60.0)
    assert np.allclose(a, b, equal_nan=True, atol=1e-9), "causal_z differs from the reference recursion"
    assert np.allclose(ou.causal_z(x[:250], 30, 60.0), a[:250], equal_nan=True), "causal_z is not prefix-invariant"
    assert ou.hash_address("0xABC") == ou.hash_address("0xabc ") != 0 and ou.hash_address(None) == 0 and ou.hash_address("nan") == 0
    raw = pd.DataFrame({"timestamp": [1520000100, 1520000200, 1520001050, 1520003100], "price": [1.0, 2.0, 1.5, 3.0], "amount": [10.0, 5.0, 2.0, 1.0],
                        "side": ["buy", "sell", "buy", "buy"], "taker": ["a", "b", "a", "c"], "maker": ["m", "m", "m", "c"]})
    t = ou.normalise_trades(raw)
    assert list(t.columns) == ou.TRADE_COLS and t["time_ns"].iloc[0] == 1520000100 * 10 ** 9
    assert list(t["buyer"]) == ["a", "m", "a", "c"] and list(t["seller"]) == ["m", "b", "m", "c"]
    bars = ou.trades_to_bars(t, 15)
    b0 = bars.iloc[0]
    assert (b0["open"], b0["high"], b0["low"], b0["close"], b0["volume"], b0["taker_buy_volume"], b0["count"]) == (1.0, 2.0, 1.0, 2.0, 15.0, 10.0, 2)
    assert (bars.index % (15 * 60 * 10 ** 9) == 0).all()
    cf = ou.carry_forward_bars(bars, 15)
    assert len(cf) == (bars.index[-1] - bars.index[0]) // (15 * 60 * 10 ** 9) + 1 and cf["close"].notna().all()
    gap = cf[cf["carried"]]
    assert len(gap) and (gap["volume"] == 0).all() and (gap["open"] == gap["close"]).all()
    w = ou.wallet_inflow_events(t, side="taker", trailing="cumulative")
    assert len(w) == 3 and np.isnan(w["size_adv"].iloc[0]) and abs(w["size_adv"].iloc[1] - 2.0 / 15.0) < 1e-12
    assert list(ou.wash_trade_flags(t)) == [False, False, False, True]          # the self-trade
    cyc = pd.DataFrame({"time_ns": [0, 10 ** 9, 5 * 10 ** 12], "amount": [100.0, 99.0, 100.0], "buyer": ["a", "b", "a"], "seller": ["b", "a", "b"]})
    assert list(ou.wash_trade_flags(cyc, window_s=3600)) == [True, True, False]
    # bursts: a burst at bar b must not depend on later bars
    cnt = pd.DataFrame({"count": np.r_[np.full(60, 3.0), 80.0, np.full(20, 3.0)] + (np.arange(81) % 3), "volume": 1.0, "taker_buy_volume": 0.5,
                        "close": 1.0}, index=np.arange(81, dtype=np.int64) * 15 * 60 * 10 ** 9)
    full = ou.trade_count_bursts(cnt, 15, warmup=10)
    part = ou.trade_count_bursts(cnt.iloc[:70], 15, warmup=10)
    assert len(full) and (full["bar_open_ns"] == 60 * 15 * 60 * 10 ** 9).any()
    assert full[full["bar_open_ns"] < 70 * 15 * 60 * 10 ** 9].reset_index(drop=True).equals(part.reset_index(drop=True))
    assert (full["time_ns"] == full["bar_open_ns"] + 15 * 60 * 10 ** 9).all(), "burst time must be the bar close"
    print("ok  onchain_utils (causal_z = reference, prefix-invariant bursts, bars, carry-forward, wallet events, wash flags)")


