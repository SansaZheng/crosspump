def test_d8():
    cfg = dict(D8_CFG, cache_dir=os.path.join(TMP, "d8_cache"))
    panel = DATASETS.get("xp_dex_wash")(cfg).build_panel()
    es = check_common(panel, "xp_dex_wash")
    m = panel.meta
    pumps = [e for e in m["episodes"] if e["is_pump"]]
    assert sorted(e["symbol"] for e in pumps) == ["AAA", "BBB"] and m["n_controls"] >= 2 and m["tokens"] == ["AAA", "BBB"]
    assert {e["key"] for e in pumps} == {"AAAETH@2018-03-05T16:00Z", "BBBETH@2018-03-07T18:00Z"}, [e["key"] for e in pumps]
    idx = {k: i for i, k in enumerate(panel.assets)}
    for e in pumps:
        i = idx[e["key"]]
        want = 48 + mf.D8[e["symbol"]]["peak_offset_min"] // 15
        assert m["peak_row"][i] == want, (e["symbol"], m["peak_row"][i], want)
        med = np.nanmedian(panel.mid[:, i])
        assert 5e-4 < med < 5e-3, f"price scale wrong (decimals / side conventions): median close {med}"
        assert e["peak_source"] == "derived_argmax_high"
    tok = d8_dex_wash.load_token_table(os.path.join(FIX, "crosspump", "victor_dex", "token_decimals.json"))
    sym_of, dec_of = dict(zip(tok["address"], tok["symbol"])), dict(zip(tok["address"], tok["decimals"]))
    lo, hi = {a: 0.0 for a in sym_of}, {a: 4e9 for a in sym_of}
    for scan, f in ((d8_dex_wash.scan_etherdelta, "EtherDeltaTrades.csv"), (d8_dex_wash.scan_idex, "IDEXTrades.csv")):
        tr = scan(os.path.join(FIX, "crosspump", "victor_dex", f), sym_of, dec_of, lo, hi, None, 5000)
        assert list(tr.columns) == d8_dex_wash.NORM_COLS and tr["price"].max() < 1.0 and 0.3 < tr["taker_buy"].mean() < 0.8 and 50 <= tr["amount"].median() <= 500, f
        if "Ether" in f:
            assert abs(tr[tr["symbol"] != "CCC"].groupby("symbol")["price"].max() - 0.05).max() < 1e-9, "planted peak price not recovered (decimals / side conventions)"
    assert np.nanmax(panel.mid) < 1.0, "a dropped row (failed IDEX tx / token-token trade) leaked into the bars"
    bbb = next(e for e in pumps if e["symbol"] == "BBB")
    assert bbb["n_messages"] == 3 and bbb["source"] == "mirtaheri+sapienza"
    cov = m["coverage"]["episodes_with_platform"]
    assert cov["wallet"] == panel.N and cov["orderflow"] >= 2 and cov["social"] >= 2
    soc = es.subset(es.platform == 0)
    assert set(soc.asset.tolist()) >= {idx[e["key"]] for e in pumps}
    i = idx[bbb["key"]]
    s_b = soc.for_asset(i)
    assert len(s_b) == 3 and np.isclose(s_b.time.min(), 48.0) and len(set(s_b.source.tolist())) == 2 and (s_b.source != 0).all()
    wal = es.subset(es.platform == 1)
    assert np.allclose(wal.avail - wal.time, np.where(wal.time + 3.0 / 15 > panel.T - 1e-6, panel.T - 1e-6 - wal.time, 3.0 / 15)), "wallet lag"
    assert (wal.source != 0).all() and np.isfinite(wal.mark[:, 1]).all() and np.isfinite(wal.mark[:, 0]).mean() > 0.9
    of = es.subset(es.platform == 2)
    assert np.allclose(of.time, np.round(of.time)) and np.allclose(of.avail, of.time), "order-flow bursts must sit on bar closes"
    counts = es.rasterise(panel.T, panel.N)
    assert counts.sum() == len(es) - int((np.ceil(es.avail) >= panel.T).sum())
    assert (panel.tradable.sum(0) > 20).all() and m["has_taker_buy"] and m["has_trade_count"]
    wl = m["wash_labels"]["per_episode"]
    assert len(wl) == panel.N and all(wl[idx[e["key"]]]["n_wash"] >= 3 for e in pumps), wl
    # cache written and re-used; identical panel on the second build
    assert len(os.listdir(cfg["cache_dir"])) == 2
    p2 = DATASETS.get("xp_dex_wash")(cfg).build_panel()
    assert np.allclose(p2.mid, panel.mid, equal_nan=True) and len(get_streams(p2)) == len(es)
    # PIT: deleting every trade later than 30 min after the BBB anchor leaves the earlier rows and events of the BBB episode unchanged
    root2 = os.path.join(TMP, "d8_trunc")
    shutil.copytree(os.path.join(FIX, "crosspump"), os.path.join(root2, "crosspump"))
    cut = int(pd.Timestamp("2018-03-07 18:30", tz="UTC").value // 10 ** 9)          # two bars after the anchor (a peak must still exist)
    for f in ("EtherDeltaTrades.csv", "IDEXTrades.csv"):
        p = os.path.join(root2, "crosspump", "victor_dex", f)
        d = pd.read_csv(p, dtype=str)
        d[d["timestamp"].astype(np.int64) < cut].to_csv(p, index=False)
    p3 = DATASETS.get("xp_dex_wash")(dict(cfg, root=root2, cache_dir=os.path.join(TMP, "d8_cache_trunc"), n_controls_per_pump=0, min_bars_frac=0.0)).build_panel()
    j = p3.assets.index(bbb["key"])
    assert np.allclose(p3.price_feat[:48, j], panel.price_feat[:48, i], equal_nan=True) and np.allclose(p3.mid[:48, j], panel.mid[:48, i], equal_nan=True)
    e_full, e_cut = es.before(i, 47.0), get_streams(p3).before(j, 47.0)
    assert len(e_full) == len(e_cut) and np.allclose(e_full.time, e_cut.time) and np.allclose(e_full.mark[:, :3], e_cut.mark[:, :3], equal_nan=True)
    expect_missing(d8_dex_wash, "xp_dex_wash", "victor_dex")
    print(f"ok  xp_dex_wash   T={panel.T} N={panel.N} pumps={m['n_pumps']} controls={m['n_controls']} events={m['coverage']['n_events']} wash={[w['n_wash'] for w in wl]}")


