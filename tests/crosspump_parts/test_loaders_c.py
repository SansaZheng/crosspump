    try:
        DATASETS.get("xp_memechain")({"root": FIX, "mode": "trades"}).build_panel()
        raise AssertionError("mode 'trades' without a trade file must raise")
    except FileNotFoundError as e:
        assert "trades.csv" in str(e)
    expect_missing(d10_memechain, "xp_memechain", "memechain")
    print(f"ok  xp_memechain  tabular: T={panel.T} N={panel.N} pumps={panel.meta['n_pumps']} | trades: T={p.T} N={p.N} pumps={m['n_pumps']} events={m['coverage']['n_events']}")


